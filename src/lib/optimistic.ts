/**
 * 乐观更新的回滚。
 *
 * 为什么要有个统一的东西：这类调用点此前各写一遍"先改本地状态 → 发请求 → 失败只在开发日志里
 * 留一行"，于是请求失败时本地状态就停在**错的那一边**（用户看到已收藏，其实库里没有），
 * 要等下一次刷新才自愈 —— 而"下一次"可能是一次页面跳转，也可能永远不来。
 *
 * 为什么不做成一个通用机制（例如包一层 useOptimistic）：**不是所有乐观更新都该回滚**。
 * 有些地方"失败就留在界面上让用户重试"比"悄悄改回去"更对（改角色、改考试目标、改设备备注
 * 都是这一类：它们本来就靠下一轮刷新收敛，硬回滚会把用户刚输入的东西抹掉）。
 * 所以这里只提供**回滚这一个动作**：调用方先改本地状态，再把"怎么改回去"和"真正的写请求"
 * 交给它。判断留在调用点，机制留在这里。
 *
 * 一条实现上的要求：`rollback` 请用**函数式更新**（`setList(prev => ...)`）只动那一项，
 * 不要用调用时捕获的整份快照 —— 两个操作重叠时（A 失败得慢、B 成功得快），快照式回滚会把
 * B 的改动一起抹掉，而按项回滚不会。
 *
 * 这个模块不 import 任何东西（那套零依赖的 Node 测试要能直接 import 它）。
 */

export interface OptimisticCommit {
  /** 请求失败时把本地状态改回原样 */
  rollback: () => void
  /** 真正的写请求 */
  commit: () => Promise<void>
  /** 失败时的出口（通常是 logError），不传就静默回滚 */
  onError?: (e: unknown) => void
}

/**
 * 提交一次乐观变更。返回是否成功 —— 调用方需要区分时用得上（多数调用点是 `void`）。
 *
 * 回滚本身抛错不会把原始错误吞掉：回滚失败时仍然把**写入失败**那个错误报出去，
 * 因为那才是排查要看的。
 */
export async function commitOptimistic(opts: OptimisticCommit): Promise<boolean> {
  try {
    await opts.commit()
    return true
  } catch (e) {
    try {
      opts.rollback()
    } catch {
      // 回滚失败也要把原始错误报出去
    }
    opts.onError?.(e)
    return false
  }
}
